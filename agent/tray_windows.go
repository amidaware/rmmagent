// TrayIcon represents the system tray icon
type TrayIcon struct {
	agent   *Agent
	version string
}

// NewTrayIcon creates a new system tray icon
func NewTrayIcon(agent *Agent, version string) *TrayIcon {
	return &TrayIcon{
		agent:   agent,
		version: version,
	}
}

// Run starts the system tray icon
func (t *TrayIcon) Run() {
	systray.Run(t.onReady, t.onExit)
}

// onReady is called when the system tray is ready
func (t *TrayIcon) onReady() {
	// Set icon and tooltip
	systray.SetIcon(getIconData())
	systray.SetTitle("Tactical RMM")
	
	// Include server URL in tooltip
	serverURL := t.agent.BaseURL
	if serverURL == "" {
		serverURL = "Not configured"
	}
	systray.SetTooltip(fmt.Sprintf("Tactical RMM Agent v%s\nServer: %s", t.version, serverURL))

	// Add menu items
	mStatus := systray.AddMenuItem("Show Status", "Display agent status information")
	systray.AddSeparator()
	mAbout := systray.AddMenuItem("About", "About Tactical RMM Agent")
	systray.AddSeparator()
	mQuit := systray.AddMenuItem("Exit", "Exit the tray icon (service keeps running)")

	// Handle menu clicks in a goroutine
	go func() {
		for {
			select {
			case <-mStatus.ClickedCh:
				t.showStatus()
			case <-mAbout.ClickedCh:
				t.showAbout()
			case <-mQuit.ClickedCh:
				systray.Quit()
				return
			}
		}
	}()
}

// onExit is called when the tray icon exits
func (t *TrayIcon) onExit() {
	// Cleanup if needed
}

// showStatus displays the agent status
func (t *TrayIcon) showStatus() {
	ShowStatus(t.version)
}

// showAbout displays the about dialog
func (t *TrayIcon) showAbout() {
	var handle w32.HWND
	msg := fmt.Sprintf("Tactical RMM Agent\nVersion: %s\nPlatform: %s/%s\n\nCopyright © 2023 AmidaWare Inc.\nLicensed under the Tactical RMM License Version 1.0",
		t.version, runtime.GOOS, runtime.GOARCH)
	w32.MessageBox(handle, msg, "About Tactical RMM", w32.MB_OK|w32.MB_ICONINFORMATION)
}

