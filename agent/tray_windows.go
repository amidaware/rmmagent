// StartTrayIcon starts the system tray icon for the agent
// This should be called from a separate goroutine or as the main process
func StartTrayIcon(agent *Agent, version string) {
	// Only run on Windows
	if runtime.GOOS != "windows" {
		return
	}

	tray := NewTrayIcon(agent, version)
	tray.Run()
}

// QuitTray quits the system tray
func QuitTray() {
	systray.Quit()
}
